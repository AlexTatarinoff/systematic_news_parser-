def SendMessageTG(msg, token, chat_id):

    import requests

    url = f"https://api.telegram.org/bot{token}/sendMessage"
    payload = {
        "chat_id": chat_id,
        "text": f'Message from code (☞ ͡° ͜ʖ ͡°)☞ \n {msg}',
        "parse_mode": "Markdown"
    }

    try:
        print("Отправка запроса в Telegram...")
        response = requests.post(url, json=payload, timeout=7)

        print(f"Статус ответа от сервера: {response.status_code}", end='. ')

        # Пытаемся безопасно распарсить JSON, только если статус 200
        if response.status_code == 200:
            try:
                result = response.json()
                if result.get("ok"):
                    print("Бот успешно прислал сообщение в Telegram")
                    return True
                else:
                    print(f"Telegram вернул ошибку: {result.get('description')}")
            except Exception as json_err:
                print(f"Telegram вернул статус 200, но ответ не JSON. Текст ответа: {response.text}")

        elif response.status_code == 401:
            print("Ошибка 401: Неверный или заблокированный токен. Перевыпустите его у @BotFather.")
        elif response.status_code == 404:
            print("Ошибка 404: Неверный URL запроса. Проверьте, что в токене нет опечаток.")
        else:
            print(f"Сервер вернул код {response.status_code}. Текст ответа: {response.text}")

    except requests.exceptions.RequestException as e:
        print(f"Сетевая ошибка (проблема с интернетом или прокси): {e}")
    except Exception as e:
        print(f"Другая непредвиденная ошибка: {e}")

    return False